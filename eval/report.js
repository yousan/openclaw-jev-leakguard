#!/usr/bin/env node
// Summarise eval/results/*.json into Markdown tables.
//   node eval/report.js            print the tables
//   node eval/report.js --readme   also write them into README.md / README.ja.md between the results markers

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'results');
const THRESHOLD = 0.5; // the plugin's default
const ORDER = ['rules', 'jev', 'kev-4b', 'kev-0.8b', 'gliner', 'gliclass'];
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
  .sort((a, b) => rank(a.label) - rank(b.label) || a.label.localeCompare(b.label));

function rank(label) {
  const i = ORDER.findIndex((o) => label === o || label.startsWith(o));
  return i < 0 ? 99 : i;
}

const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : '–');
const frac = (n, d) => `${pct(n, d)} (${n}/${d})`;
function quantile(xs, q) {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(q * s.length))];
}
const ms = (x) => (x == null ? '–' : x < 1 ? '<1 ms' : x < 1000 ? `${Math.round(x)} ms` : `${(x / 1000).toFixed(1)} s`);

const maxScore = (r) => Math.max(0, ...Object.values(r.model?.scores || {}));
const regexBlind = (r) => r.known === false || (r.known === undefined && !r.rules.flagged);

function row(results, flag, latency) {
  const leaks = results.filter((r) => r.label === 'leak');
  const clean = results.filter((r) => r.label === 'clean');
  const blind = leaks.filter(regexBlind);
  return {
    miss: frac(leaks.filter((r) => !flag(r)).length, leaks.length),
    missBlind: frac(blind.filter((r) => !flag(r)).length, blind.length),
    fp: frac(clean.filter(flag).length, clean.length),
    p50: ms(quantile(results.map(latency), 0.5)),
    p95: ms(quantile(results.map(latency), 0.95)),
  };
}

/** Lowest miss rate the model reaches (rules + model) while keeping false alarms at or under `budget`. */
function atBudget(results, budget = 0.1) {
  const leaks = results.filter((r) => r.label === 'leak');
  const clean = results.filter((r) => r.label === 'clean');
  let best = null;
  for (let t = 0.05; t < 1.0; t += 0.01) {
    const flag = (r) => r.rules.flagged || maxScore(r) >= t;
    const fp = clean.filter(flag).length / clean.length;
    if (fp > budget) continue;
    const miss = leaks.filter((r) => !flag(r)).length;
    if (!best || miss < best.miss) best = { miss, t };
  }
  return best ? `${pct(best.miss, leaks.length)} @ ${best.t.toFixed(2)}` : '–';
}

const judgeName = (f) =>
  ({ jev: 'Jev (`typesafe/jev-latest`)', 'kev-4b': 'Kev-4B (`typesafe/kev-latest`)', 'kev-0.8b': 'Kev-0.8B (`typesafe/kev-latest`)', 'gliner2.5-small': 'GLiNER2.5 small (`onnx/gliner2.5-small-v1`)', 'gliclass-edge': 'GLiClass edge (`onnx/gliclass-edge-v3.0`)' })[f.label] || f.label;
const where = (f) => (f.backend === 'none' ? 'nowhere' : f.local === false || /jev/.test(f.backend) ? '**TypeSafe API**' : 'this machine');

const main = [];
const alone = [];
for (const f of files) {
  const R = f.results;
  if (f.backend === 'none' || !R[0]?.model) {
    main.push({ name: 'Rules only (regex + your term lists)', where: 'nowhere', hw: '', ...row(R, (r) => r.rules.flagged, (r) => r.rules.ms), budget: '–' });
    continue;
  }
  const hw = f.machine ? ` ${f.machine}` : '';
  main.push({
    name: `Rules + ${judgeName(f)}`,
    where: where(f),
    hw,
    ...row(R, (r) => r.rules.flagged || r.model.flagged, (r) => (r.rules.flagged ? r.rules.ms : r.model.ms)),
    budget: atBudget(R),
  });
  alone.push({ name: judgeName(f), ...row(R, (r) => r.model.flagged, (r) => r.model.ms) });
}

const n = files[0]?.results.length ?? 0;
const table1 =
  `| Judge (\`decisionModel\`) | Text goes to | Missed leaks | …that a regex can't see | False alarms | Missed at ≤10% false alarms | Latency p50 | p95 |\n|---|---|---|---|---|---|---|---|\n` +
  main.map((r) => `| ${r.name} | ${r.where} | ${r.miss} | ${r.missBlind} | ${r.fp} | ${r.budget} | ${r.p50} | ${r.p95}${r.hw ? ` (${r.hw.trim()})` : ''} |`).join('\n');
const table2 =
  `| Model alone, no rules | Missed leaks | …that a regex can't see | False alarms | p50 |\n|---|---|---|---|---|\n` +
  alone.map((r) => `| ${r.name} | ${r.miss} | ${r.missBlind} | ${r.fp} | ${r.p50} |`).join('\n');
const out = `${table1}\n\n${table2}\n\n<sub>${n} synthetic cases, threshold ${THRESHOLD}, every case judged as if going to a public channel. "Missed at ≤10% false alarms" picks the best threshold on this same set, so it is optimistic. Generated by \`node eval/report.js\`.</sub>`;
console.log(out);

if (process.argv.includes('--readme')) {
  for (const name of ['README.md', 'README.ja.md']) {
    const p = join(here, '..', name);
    let s;
    try {
      s = readFileSync(p, 'utf8');
    } catch {
      continue;
    }
    const re = /(<!-- results:start -->\n)[\s\S]*?(\n<!-- results:end -->)/;
    if (re.test(s)) writeFileSync(p, s.replace(re, `$1${out}$2`));
  }
}
